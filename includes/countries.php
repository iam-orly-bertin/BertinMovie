/** Retire les accents pour trier correctement (É après E, etc.) */
function bm_ascii($s)
{
    static $map = null;
    if ($map === null) {
        $map = [
            'À'=>'A','Â'=>'A','Ä'=>'A','Å'=>'A','Ã'=>'A','Á'=>'A','à'=>'a','â'=>'a','ä'=>'a','å'=>'a','ã'=>'a','á'=>'a',
            'Ç'=>'C','ç'=>'c','È'=>'E','É'=>'E','Ê'=>'E','Ë'=>'E','è'=>'e','é'=>'e','ê'=>'e','ë'=>'e',
            'Î'=>'I','Ï'=>'I','Í'=>'I','î'=>'i','ï'=>'i','í'=>'i','Ñ'=>'N','ñ'=>'n',
            'Ô'=>'O','Ö'=>'O','Ó'=>'O','Ø'=>'O','Õ'=>'O','ô'=>'o','ö'=>'o','ó'=>'o','ø'=>'o','õ'=>'o',
            'Ù'=>'U','Û'=>'U','Ü'=>'U','Ú'=>'U','ù'=>'u','û'=>'u','ü'=>'u','ú'=>'u','Ý'=>'Y','ý'=>'y','ÿ'=>'y',
            'Ā'=>'A','ā'=>'a','Ō'=>'O','ō'=>'o','Ś'=>'S','ś'=>'s','Š'=>'S','š'=>'s','Ž'=>'Z','ž'=>'z','Č'=>'C','č'=>'c','Ł'=>'L','ł'=>'l',
            'œ'=>'oe','Œ'=>'OE','æ'=>'ae','Æ'=>'AE','ß'=>'ss',
        ];
    }
    return strtolower(strtr($s, $map));
}

/** Pays triés dans la langue demandée : code => nom */
function bm_countries_sorted($lang)
{
    global $BM_COUNTRIES;
    $i = ($lang === 'en') ? 1 : 0;
    $list = [];
    foreach ($BM_COUNTRIES as $code => $names) {
        $list[$code] = $names[$i];
    }
    uasort($list, function ($a, $b) {
        return strcmp(bm_ascii($a), bm_ascii($b));
    });
    return $list;
}

/**
 * Renvoie l'id_pays de la table `pays` pour un code ISO.
 * - réutilise la ligne existante si le pays y est déjà (ex : "burundi", "USA", "indian")
 * - sinon l'ajoute automatiquement (nom français, en minuscules comme tes données actuelles)
 */
function bm_country_id(PDO $pdo, $code)
{
    global $BM_COUNTRIES;
    if (!isset($BM_COUNTRIES[$code])) {
        return null;
    }
    $lower = function ($s) {
        return function_exists('mb_strtolower') ? mb_strtolower($s, 'UTF-8') : strtolower($s);
    };
    $fr = $lower($BM_COUNTRIES[$code][0]);
    $en = $lower($BM_COUNTRIES[$code][1]);

    // Anciennes écritures déjà présentes dans ta base
    $alias = ['US' => ['usa', 'etats-unis'], 'IN' => ['indian', 'inde'], 'GB' => ['uk', 'angleterre']];
    $candidats = array_merge([$fr, $en], $alias[$code] ?? []);

    $sel = $pdo->prepare("SELECT id_pays FROM pays WHERE nom_pays = ? LIMIT 1");
    foreach ($candidats as $nom) {
        $sel->execute([$nom]);
        $id = $sel->fetchColumn();
        if ($id) {
            return (int) $id;
        }
    }
    try {
        $pdo->prepare("INSERT INTO pays (nom_pays) VALUES (?)")->execute([$fr]);
        return (int) $pdo->lastInsertId();
    } catch (PDOException $e) {
        // inséré en même temps par quelqu'un d'autre : on relit
        $sel->execute([$fr]);
        $id = $sel->fetchColumn();
        return $id ? (int) $id : null;
    }
}